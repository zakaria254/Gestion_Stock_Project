<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Http\Requests\StoreUpdateStockMovementRequest;
use App\Http\Resources\StockMovementResource;
use App\Models\StockMovement;
use Illuminate\Support\Facades\DB;

class StockMovementController extends Controller
{
    /**
     * Display a listing of the resource.
     */
    public function index()
    {
        $movements = StockMovement::with('stock.article')->latest()->paginate($this->perPage());

        return StockMovementResource::collection($movements);
    }

    /**
     * Store a newly created resource in storage.
     */
    public function store(StoreUpdateStockMovementRequest $request)
    {
        // the observer updates the stock: both writes succeed or neither does
        $movement = DB::transaction(fn () => StockMovement::create($request->validated()));

        $movement->load('stock.article');

        return (new StockMovementResource($movement))->response()->setStatusCode(201);
    }

    /**
     * Display the specified resource.
     */
    public function show(StockMovement $movement)
    {
        return new StockMovementResource($movement->load('stock.article'));
    }

    /**
     * Update the specified resource in storage.
     */
    public function update(StoreUpdateStockMovementRequest $request, StockMovement $movement)
    {
        if ($movement->is_generated) {
            return $this->generatedMovementResponse();
        }

        DB::transaction(fn () => $movement->update($request->validated()));

        return new StockMovementResource($movement->load('stock.article'));
    }

    /**
     * Remove the specified resource from storage.
     */
    public function destroy(StockMovement $movement)
    {
        if ($movement->is_generated) {
            return $this->generatedMovementResponse();
        }

        DB::transaction(fn () => $movement->delete());

        return response()->noContent();
    }

    private function generatedMovementResponse()
    {
        return response()->json([
            'message' => 'This movement was generated by a sale or a production lot and can not be changed.',
        ], 409);
    }
}
